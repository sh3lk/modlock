package main

import (
	"bytes"
	"fmt"
	"slices"
	"strings"
	"unicode"
)

// rustHeader opens each generated Rust module, which reads the handwritten
// module that declares it.
const rustHeader = "// Code generated by modlock-entitygen. DO NOT EDIT.\n\nuse super::*;\n"

// rustFiles names the module of each class that roots a large subtree. Every
// other class goes in its base's module, and the root in classes, so a game
// update moves a class between modules only when it changes the class's base.
var rustFiles = map[string]string{
	"CBaseModelEntity":    "models",
	"CCitadelBaseAbility": "abilities",
}

// rustNumbers maps each numeric wire field type to its Rust type.
var rustNumbers = map[string]string{
	"int8":    "i8",
	"int16":   "i16",
	"int32":   "i32",
	"uint8":   "u8",
	"uint16":  "u16",
	"uint32":  "u32",
	"int64":   "i64",
	"uint64":  "u64",
	"float32": "f32",
	"float64": "f64",
}

// rustElements maps each other wire field type to the Rust type of one value.
// A handle to a class the libraries lack, and each handle of a list, names
// its entity as the root class.
var rustElements = map[string]string{
	"bool":   "bool",
	"string": "String",
	"vector": "Vector",
	"handle": "CEntityInstance",
}

// rustValues maps each value to the type a key holds and an input takes.
var rustValues = map[value]string{
	"boolean": "bool",
	"integer": "i32",
	"number":  "f32",
	"text":    "String",
	"vector":  "Vector",
	"color":   "u32",
	"angles":  "Angles",
}

// rustConsoleTypes maps the Go type of a console variable's value to its Rust
// type.
var rustConsoleTypes = map[string]string{
	"bool":    "bool",
	"int8":    "i8",
	"uint8":   "u8",
	"int16":   "i16",
	"uint16":  "u16",
	"int32":   "i32",
	"uint32":  "u32",
	"int64":   "i64",
	"uint64":  "u64",
	"float32": "f32",
	"float64": "f64",
	"string":  "String",
}

// rustMethods are the names the library gives every class, rustEntity the
// functions of module entity and rustConsole those of module console. A
// generated name that is one of them takes an underscore after it.
var (
	rustMethods = []string{"handle", "field", "of", "cast"}
	rustEntity  = []string{"send"}
	rustConsole = []string{"apply", "arena"}
)

// writeRust writes modules entity and console as Rust source files. Module
// entity holds the classes with their field accessors, split by rustFiles,
// the classes' input methods, the key value structs and the designer names.
// Each class wraps its base, which it dereferences to, so a class has its
// bases' accessors and inputs. Each field is one method returning a value
// that gets and sets the field. Module console holds a function per console
// variable and command.
//
// Every name is the game's, as the other libraries have it, so a class, a
// field, a key or a console variable is found in Rust under the name the
// game's schema and the other libraries' examples give it. A designer name
// and a console entry are functions rather than constants: a constant with a
// small-letter name would capture every binding of that name in a module that
// imports it, since Rust reads such a binding as a pattern of the constant.
func writeRust(s *schema, classes []*class, e *entities, c *console) map[string][]byte {
	// Write each class after the root, in its subtree's module.
	sources := map[string]*bytes.Buffer{"classes": bytes.NewBufferString(rustHeader)}
	fileOf := map[string]string{classes[0].name: "classes"}
	methods := map[*class]map[string]bool{}
	for _, c := range classes[1:] {
		// Write the class.
		file := rustFiles[c.name]
		if file == "" {
			file = fileOf[c.base]
		} else {
			sources[file] = bytes.NewBufferString(rustHeader)
		}
		fileOf[c.name] = file
		out := sources[file]
		fmt.Fprintf(out, "\nclass!(%s: %s);\n", c.name, c.base)

		// Write a method per field. A class may list a field twice; keep the
		// first.
		taken := map[string]bool{}
		methods[c] = taken
		var body bytes.Buffer
		for _, f := range s.readableFields(c) {
			method := rustName(f.name, rustMethods)
			if taken[method] {
				continue
			}
			taken[method] = true
			if body.Len() != 0 {
				body.WriteString("\n")
			}
			fmt.Fprintf(&body, "    pub fn %s(self) -> %s {\n        self.field(%q)\n    }\n", method, rustField(f), f.name)
		}
		if body.Len() != 0 {
			fmt.Fprintf(out, "\nimpl %s {\n%s}\n", c.name, body.String())
		}
	}
	files := map[string][]byte{}
	for file, out := range sources {
		files["entity/"+file+".gen.rs"] = out.Bytes()
	}

	// Write a method per input, unless a field took its name.
	out := bytes.NewBufferString(rustHeader)
	for _, c := range classes[1:] {
		var body bytes.Buffer
		for _, in := range e.inputs[c.name] {
			method := "input_" + in.name
			if methods[c][method] {
				continue
			}
			methods[c][method] = true
			if body.Len() != 0 {
				body.WriteString("\n")
			}
			body.WriteString(wrap("    /// ", rustDoc(method+" sends "+in.name+". "+sentence(in.description))))
			parameter, argument := "", "None"
			switch in.value {
			case "":
			case "text":
				parameter, argument = ", value: &str", "Some(value.into())"
			default:
				parameter, argument = ", value: "+rustValues[in.value], "Some(value.into())"
			}
			fmt.Fprintf(&body, "    pub fn %s(self%s) -> bool {\n        send(self.handle, %q, %s)\n    }\n", method, parameter, in.name, argument)
		}
		if body.Len() != 0 {
			fmt.Fprintf(out, "\nimpl %s {\n%s}\n", c.name, body.String())
		}
	}
	files["entity/inputs.gen.rs"] = out.Bytes()

	// Write each data description's key value struct, which holds its base's
	// and dereferences to it, so each key is declared once and a mod sets a
	// base's key as it sets the struct's own.
	out = bytes.NewBufferString(rustHeader)
	for _, m := range e.keyMaps {
		named := map[string]bool{}
		var fields, entries bytes.Buffer
		for _, k := range m.keys {
			name := rustName(k.name, []string{"base"})
			if named[name] {
				continue
			}
			named[name] = true
			fmt.Fprintf(&fields, "    pub %s: Option<%s>,\n", name, rustValues[k.value])
			fmt.Fprintf(&entries, " %s => %q,", name, k.name)
		}
		base, parent := "", ""
		if m.base != nil {
			base = fmt.Sprintf("    /// base holds the keys of %s.\n    pub base: %sKeys,\n", m.base.name, m.base.name)
			parent = ": " + m.base.name + "Keys"
		}
		fmt.Fprintf(out, "\n/// %sKeys are the spawn key values %s adds to its base's.\n", m.name, m.name)
		fmt.Fprintf(out, "#[derive(Clone, Debug, Default, PartialEq)]\npub struct %sKeys {\n%s%s}\n", m.name, base, fields.String())
		fmt.Fprintf(out, "keys!(%sKeys%s {%s });\n", m.name, parent, strings.TrimSuffix(entries.String(), ","))
	}
	files["entity/keys.gen.rs"] = out.Bytes()

	// Write each designer name.
	out = bytes.NewBufferString(rustHeader)
	for _, d := range e.designers {
		fmt.Fprintf(out, "\npub const fn %s() -> Designer<%s, %sKeys> {\n    Designer::new(%q, %q)\n}\n", rustName(d.name, rustEntity), d.class, d.keys.name, d.name, d.subclass)
	}
	files["entity/designers.gen.rs"] = out.Bytes()

	// Write each console variable and command, unless another took its name.
	taken := map[string]bool{}
	consoleFiles := []struct {
		name    string
		entries []consoleEntry
	}{{"console/variables.gen.rs", c.variables}, {"console/commands.gen.rs", c.commands}}
	for _, file := range consoleFiles {
		out = bytes.NewBufferString(rustHeader)
		for _, entry := range file.entries {
			name := rustName(entry.name, rustConsole)
			if taken[name] {
				continue
			}
			taken[name] = true
			out.WriteString("\n")
			if help := sentence(entry.help); help != "" {
				out.WriteString(wrap("/// ", rustDoc(help)))
			}
			if entry.typ == "" {
				fmt.Fprintf(out, "pub const fn %s() -> Command {\n    Command::new(%q)\n}\n", name, entry.name)
			} else {
				fmt.Fprintf(out, "pub const fn %s() -> Variable<%s> {\n    Variable::new(%q)\n}\n", name, rustConsoleTypes[entry.typ], entry.name)
			}
		}
		files[file.name] = out.Bytes()
	}
	return files
}

// rustField returns the type of the accessor of field f.
func rustField(f readable) string {
	element := rustNumbers[f.wire]
	if element == "" {
		element = rustElements[f.wire]
	}
	switch {
	case f.list:
		return "List<" + element + ">"
	case f.angles:
		return "Field<Angles>"
	case f.target != "":
		return "Handle<" + f.target + ">"
	case f.wire == "handle":
		return "Handle<CEntityInstance>"
	}
	return "Field<" + element + ">"
}

// rustDoc returns text as a doc comment holds it: without the marks rustdoc
// reads as a link, a tag or code.
func rustDoc(text string) string {
	return strings.NewReplacer("[", `\[`, "]", `\]`, "<", `\<`, ">", `\>`, "`", "'").Replace(text)
}

// rustKeywords are the reserved words of Rust, which a name cannot use.
var rustKeywords = strings.Fields(`abstract as async await become box break const continue crate do dyn
	else enum extern false final fn for gen if impl in let loop macro match mod move mut override
	priv pub ref return self static struct super trait true try type typeof unsafe unsized use
	virtual where while yield`)

// rustUnraw are the reserved words Rust takes no raw identifier of.
var rustUnraw = []string{"crate", "self", "super", "Self", "_"}

// rustName returns the game's name as Rust can spell it: the name itself; a
// reserved word of Rust as the raw identifier of it, such as r#box, so the
// name stays the game's; with an underscore after a word Rust has no raw
// identifier of and after a name in taken, which the library has; and behind
// an f when it starts with a digit.
func rustName(name string, taken []string) string {
	if unicode.IsDigit([]rune(name)[0]) {
		name = "f" + name
	}
	switch {
	case slices.Contains(rustUnraw, name) || slices.Contains(taken, name):
		return name + "_"
	case slices.Contains(rustKeywords, name):
		return "r#" + name
	}
	return name
}
