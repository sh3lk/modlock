// rustNames renames calls the Rust library wraps by hand: its log! formats
// its arguments.
var rustNames = map[string]string{"Log": "log_line"}

// rustPreamble opens the generated module with the handwritten parts of the
// library it names.
const rustPreamble = `// Code generated by modlock-sdkgen. DO NOT EDIT.

use crate::heroes::hero_name;
use crate::host;
use crate::wire::{self, Message};
use crate::Player;

`

// rustKind is how the Rust library holds and encodes one scalar wire type.
type rustKind struct {
	// name is the name of the kind's functions in the wire module.
	name string
	// wire is the wire module's constant for the kind's wire type.
	wire string
	// typ is the Rust type that holds a value.
	typ string
}

// rustKinds maps each scalar wire type the schema uses to its Rust form. An
// enum travels as an int32.
var rustKinds = map[descriptorpb.FieldDescriptorProto_Type]rustKind{
	descriptorpb.FieldDescriptorProto_TYPE_DOUBLE:  {"double", "FIXED64", "f64"},
	descriptorpb.FieldDescriptorProto_TYPE_FLOAT:   {"float", "FIXED32", "f32"},
	descriptorpb.FieldDescriptorProto_TYPE_INT32:   {"int32", "VARINT", "i32"},
	descriptorpb.FieldDescriptorProto_TYPE_INT64:   {"int64", "VARINT", "i64"},
	descriptorpb.FieldDescriptorProto_TYPE_UINT32:  {"uint32", "VARINT", "u32"},
	descriptorpb.FieldDescriptorProto_TYPE_UINT64:  {"uint64", "VARINT", "u64"},
	descriptorpb.FieldDescriptorProto_TYPE_FIXED32: {"fixed32", "FIXED32", "u32"},
	descriptorpb.FieldDescriptorProto_TYPE_FIXED64: {"fixed64", "FIXED64", "u64"},
	descriptorpb.FieldDescriptorProto_TYPE_BOOL:    {"bool", "VARINT", "bool"},
	descriptorpb.FieldDescriptorProto_TYPE_STRING:  {"string", "LEN", "String"},
	descriptorpb.FieldDescriptorProto_TYPE_BYTES:   {"bytes", "LEN", "Vec<u8>"},
	descriptorpb.FieldDescriptorProto_TYPE_ENUM:    {"int32", "VARINT", ""},
}

// rustWriter writes the Rust library's generated module.
type rustWriter struct {
	*directions
	s     *schema
	out   bytes.Buffer
	calls []*call
	// types reaches every message and enum the module declares.
	types reach
	// names holds the schema name of each type the module declares by its
	// Rust name, which drops the underscores of a nested name.
	names map[string]string
	// absent holds each single message field of the services outside Modlock,
	// which is None when a reply leaves it out, as protobuf's presence has it.
	absent map[*field]bool
	// spared holds each name of rustSpare the schema has a field for.
	spared map[string]bool
}

// writeRust returns rust/modlock/src/host.gen.rs.
func writeRust(s *schema) ([]byte, error) {
	calls, err := s.calls()
	if err != nil {
		return nil, err
	}
	w := &rustWriter{directions: s.directions(calls), s: s, calls: calls, names: map[string]string{}, absent: map[*field]bool{}, spared: map[string]bool{}}
	s.serviceAbsent(w.absent)

	// Reach the vector types, what the calls and events carry, what the
	// handwritten library sends for the calls it makes itself, and the
	// messages of the services outside Modlock.
	for _, name := range []string{".modlock.geometry.Vec3", ".modlock.geometry.EulerAngles"} {
		m := s.messages[name]
		if m == nil {
			return nil, fmt.Errorf("the schema lacks %s", name)
		}
		w.types.add(m)
	}
	for _, c := range calls {
		if c.options {
			w.types.add(c.method.request)
		}
		for _, p := range c.params {
			for _, f := range p.fields() {
				w.types.addField(f)
			}
		}
		if c.result != nil {
			w.types.addField(c.result)
		}
	}
	for _, m := range s.mod.methods {
		w.types.add(m.request)
		w.types.add(m.response)
	}
	for _, m := range s.host.methods {
		if skipped[m.name] {
			w.types.add(m.request)
			w.types.add(m.response)
		}
	}
	for _, m := range s.services {
		w.types.add(m)
	}

	// Write the types in schema order, then the classes, calls and events.
	w.out.WriteString(rustPreamble)
	for _, e := range s.enumOrder {
		if w.types.seen[e] {
			if err := w.declare(rustType(e.name), e.full); err != nil {
				return nil, err
			}
			w.writeEnum(e)
		}
	}
	for _, m := range s.messageOrder {
		if !w.types.seen[m] || m.isEmpty() {
			continue
		}
		if err := w.declare(w.messageName(m), m.full); err != nil {
			return nil, err
		}
		if m.isUnion() {
			err = w.writeUnion(m)
		} else {
			err = w.writeStruct(m)
		}
		if err != nil {
			return nil, fmt.Errorf("%s: %w", m.name, err)
		}
	}
	for _, c := range calls {
		for _, p := range c.params {
			if p.oneof == nil {
				continue
			}
			name := w.argumentName(c.method.request, p.oneof)
			if err := w.declare(name, c.method.request.full+"."+p.oneof.name); err != nil {
				return nil, err
			}
			w.writeOneof(name, c.method.request, p.oneof)
		}
	}
	for _, c := range classes {
		if err := w.writeClass(c); err != nil {
			return nil, err
		}
	}
	for _, c := range calls {
		if c.class == nil {
			if err := w.writeCall(c, 0); err != nil {
				return nil, fmt.Errorf("%s: %w", c.method.name, err)
			}
			w.out.WriteString("\n")
		}
	}
	if err := w.writeMod(); err != nil {
		return nil, err
	}
	w.writeRoundTrip()
	if len(w.spared) != len(rustSpare) {
		return nil, fmt.Errorf("rustSpare names a field the schema lacks")
	}
	return w.out.Bytes(), nil
}

// declare records that the module declares a type named name for the schema's
// full, and fails when another type already took the name.
func (w *rustWriter) declare(name, full string) error {
	if other, ok := w.names[name]; ok {
		return fmt.Errorf("%s and %s share the Rust name %s", other, full, name)
	}
	w.names[name] = full
	return nil
}

// line writes one line of code at depth levels of indentation.
func (w *rustWriter) line(depth int, format string, args ...any) {
	w.out.WriteString(strings.Repeat("    ", depth))
	fmt.Fprintf(&w.out, format, args...)
	w.out.WriteByte('\n')
}

// lines writes each of lines at depth levels of indentation.
func (w *rustWriter) lines(depth int, lines []string) {
	for _, line := range lines {
		w.line(depth, "%s", line)
	}
}

// doc writes text as a doc comment at depth levels of indentation.
func (w *rustWriter) doc(depth int, text string) {
	writeComment(&w.out, strings.Repeat("    ", depth), "///", text)
}

// messageName returns the Rust name of a message.
func (w *rustWriter) messageName(m *message) string {
	if name := mapped(m); name != "" {
		return name
	}
	return rustType(m.name)
}

// writeEnum writes an enum with the conversion from its number. A number the
// library has no name for reads as the enum's unset value.
func (w *rustWriter) writeEnum(e *enum) {
	name := rustType(e.name)
	unset := ""
	w.doc(0, rename(e.doc, e.name, name))
	w.line(0, "#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]")
	w.line(0, "#[repr(i32)]")
	w.line(0, "pub enum %s {", name)
	for _, v := range e.values {
		variant := rustVariant(e.valueName(v))
		w.doc(1, rename(v.doc, v.name, variant))
		if v.number == 0 && unset == "" {
			unset = variant
			w.line(1, "#[default]")
		}
		w.line(1, "%s = %d,", variant, v.number)
	}
	w.line(0, "}")
	w.line(0, "")
	w.line(0, "impl %s {", name)
	w.doc(1, fmt.Sprintf("from_i32 returns the %s numbered number, or %s for a number the library\nhas no name for.", name, unset))
	w.line(1, "pub fn from_i32(number: i32) -> Self {")
	w.line(2, "match number {")
	for _, v := range e.values {
		w.line(3, "%d => Self::%s,", v.number, rustVariant(e.valueName(v)))
	}
	w.line(3, "_ => Self::%s,", unset)
	w.line(2, "}")
	w.line(1, "}")
	w.line(0, "}")
	w.line(0, "")
}

// member is one member of a struct: a field, or a oneof standing for its
// cases.
type member struct {
	field *field
	oneof *oneof
}

// members returns the members of the struct of m: its fields in schema order
// without the receiver an options message leaves out, with each oneof at the
// place of its first case.
func (w *rustWriter) members(m *message) []member {
	var members []member
	for _, f := range m.fields {
		switch {
		case f == w.omitted[m]:
		case f.oneof == nil:
			members = append(members, member{field: f})
		case f.oneof.fields[0] == f:
			members = append(members, member{oneof: f.oneof})
		}
	}
	return members
}

// writeStruct writes a message as a struct, the enum of each of its oneofs,
// and its encoding.
func (w *rustWriter) writeStruct(m *message) error {
	name := w.messageName(m)
	members := w.members(m)

	// Declare the struct.
	w.doc(0, rename(m.doc, m.name, name))
	if mapped(m) != "" {
		// A vector is three numbers, which a mod passes by value.
		w.line(0, "#[derive(Clone, Copy, Debug, Default, PartialEq)]")
	} else {
		w.line(0, "#[derive(Clone, Debug, Default, PartialEq)]")
	}
	w.line(0, "pub struct %s {", name)
	for _, member := range members {
		if o := member.oneof; o != nil {
			w.doc(1, pythonFieldDoc(m, rename(o.doc, camel(o.name), o.name)))
			w.line(1, "pub %s: Option<%s>,", rustIdent(o.name), w.oneofName(m, o))
			continue
		}
		doc := pythonFieldDoc(m, member.field.doc)
		if w.nobody(member.field) {
			if member.field.kind != descriptorpb.FieldDescriptorProto_TYPE_INT32 {
				return fmt.Errorf("%s holds nobody as -1, but is no int32", member.field.name)
			}
			doc += "\nNone stands for the schema's -1."
		}
		w.doc(1, doc)
		w.line(1, "pub %s: %s,", rustIdent(member.field.name), w.memberType(m, member.field))
	}
	w.line(0, "}")
	w.line(0, "")
	for _, o := range m.oneofs {
		w.writeOneof(w.oneofName(m, o), m, o)
	}

	// A message without members encodes as nothing.
	w.line(0, "impl Message for %s {", name)
	if len(members) == 0 {
		w.line(1, "fn encode(&self, _out: &mut Vec<u8>) {}")
		w.line(0, "")
		w.line(1, "fn decode(_data: &[u8]) -> Result<Self, wire::Error> {")
		w.line(2, "Ok(Self::default())")
		w.line(1, "}")
		w.line(0, "}")
		w.line(0, "")
		return nil
	}

	// Encode each member the receiver would not assume.
	w.line(1, "fn encode(&self, out: &mut Vec<u8>) {")
	for _, member := range members {
		if o := member.oneof; o != nil {
			w.line(2, "match &self.%s {", rustIdent(o.name))
			for _, f := range o.fields {
				w.line(3, "Some(%s::%s(v)) => %s", w.oneofName(m, o), rustVariant(f.name), w.one(f, w.caseValue(m, f)))
			}
			w.line(3, "None => {}")
			w.line(2, "}")
			continue
		}
		w.lines(2, w.encode(member.field, "self."+rustIdent(member.field.name), false, w.boxed(m, member.field)))
	}
	w.line(1, "}")
	w.line(0, "")

	// Decode the fields by number, skipping the ones the library does not
	// know.
	w.line(1, "fn decode(data: &[u8]) -> Result<Self, wire::Error> {")
	w.line(2, "let mut message = Self::default();")
	for _, f := range m.fields {
		// A slot the sender left out is slot 0, which a player holds.
		if f != w.omitted[m] && f.oneof == nil && w.nobody(f) {
			w.line(2, "message.%s = %s;", rustIdent(f.name), classOf(f).rustKnown("0"))
		}
	}
	w.line(2, "let mut r = wire::Reader::new(data);")
	w.line(2, "while let Some((number, kind)) = r.field()? {")
	w.line(3, "match number {")
	for _, f := range m.fields {
		if f == w.omitted[m] {
			continue
		}
		arm, err := w.decode(m, f, "message."+rustIdent(f.name))
		if err != nil {
			return err
		}
		w.line(4, "%d => %s,", f.number, arm)
	}
	w.line(4, "_ => r.skip(kind)?,")
	w.line(3, "}")
	w.line(2, "}")
	w.line(2, "Ok(message)")
	w.line(1, "}")
	w.line(0, "}")
	w.line(0, "")
	return nil
}

// oneofName returns the name of the enum of the oneof o of m.
func (w *rustWriter) oneofName(m *message, o *oneof) string {
	return w.messageName(m) + camel(o.name)
}

// argumentName returns the name of the enum a call takes for the oneof o of
// its request: the request's name without its suffix, then the oneof's
// unless the name ends with it, so SelectHeroRequest's hero is SelectHero.
func (w *rustWriter) argumentName(request *message, o *oneof) string {
	name := strings.TrimSuffix(w.messageName(request), "Request")
	if !strings.HasSuffix(name, camel(o.name)) {
		name += camel(o.name)
	}
	return name
}

// writeOneof writes the enum named name of the oneof o of m, one variant for
// each case.
func (w *rustWriter) writeOneof(name string, m *message, o *oneof) {
	w.doc(0, fmt.Sprintf("%s is the %s of %s.", name, o.name, article(w.messageName(m))))
	w.line(0, "#[derive(Clone, Debug, PartialEq)]")
	w.line(0, "pub enum %s {", name)
	for _, f := range o.fields {
		w.doc(1, rename(f.doc, camel(f.name), rustVariant(f.name)))
		w.line(1, "%s(%s),", rustVariant(f.name), w.caseType(m, f))
	}
	w.line(0, "}")
	w.line(0, "")
}

// caseType returns the type the variant of the case f of m holds.
func (w *rustWriter) caseType(m *message, f *field) string {
	if w.boxed(m, f) {
		return "Box<" + w.base(f) + ">"
	}
	return w.base(f)
}

// caseValue returns the expression that encodes v, the reference a match
// binds to the variant of the case f of m.
func (w *rustWriter) caseValue(m *message, f *field) string {
	switch {
	case w.boxed(m, f):
		return "&**v"
	case w.copies(f):
		return "*v"
	}
	return "v"
}

// writeUnion writes a message holding only a oneof as the enum of its cases,
// which stands for the message wherever a field holds it.
func (w *rustWriter) writeUnion(m *message) error {
	name := w.messageName(m)
	o := m.oneofs[0]
	w.doc(0, rename(m.doc, m.name, name))
	w.line(0, "#[derive(Clone, Debug, PartialEq)]")
	w.line(0, "pub enum %s {", name)
	for _, f := range o.fields {
		w.doc(1, rename(f.doc, camel(f.name), rustVariant(f.name)))
		w.line(1, "%s(%s),", rustVariant(f.name), w.caseType(m, f))
	}
	w.line(0, "}")
	w.line(0, "")

	// Encode the case the value holds.
	w.line(0, "impl %s {", name)
	w.doc(1, fmt.Sprintf("encode appends the %s to out.", name))
	w.line(1, "pub fn encode(&self, out: &mut Vec<u8>) {")
	w.line(2, "match self {")
	for _, f := range o.fields {
		w.line(3, "Self::%s(v) => %s", rustVariant(f.name), w.one(f, w.caseValue(m, f)))
	}
	w.line(2, "}")
	w.line(1, "}")
	w.line(0, "")

	// Decode the last case data holds, or none.
	w.doc(1, fmt.Sprintf("decode returns the %s in data, or None when data holds no case.", name))
	w.line(1, "pub fn decode(data: &[u8]) -> Result<Option<Self>, wire::Error> {")
	w.line(2, "let mut value = None;")
	w.line(2, "let mut r = wire::Reader::new(data);")
	w.line(2, "while let Some((number, kind)) = r.field()? {")
	w.line(3, "match number {")
	for _, f := range o.fields {
		value, err := w.value(f)
		if err != nil {
			return err
		}
		if w.boxed(m, f) {
			value = "Box::new(" + value + ")"
		}
		w.line(4, "%d => value = Some(Self::%s(%s)),", f.number, rustVariant(f.name), value)
	}
	w.line(4, "_ => r.skip(kind)?,")
	w.line(3, "}")
	w.line(2, "}")
	w.line(2, "Ok(value)")
	w.line(1, "}")
	w.line(0, "}")
	w.line(0, "")
	return nil
}

// rustSpare are the single message fields a struct holds behind a pointer
// though it could hold them whole, each named by its message and its field.
// Most values leave such a field unset, and the library keeps many values at
// once: an interface node has a style for the pointer over it, for its
// arrival, for its leaving and for its cycle, and most nodes set none of
// them. Unset, each takes a pointer in place of a whole style.
var rustSpare = map[string]bool{
	"Node.hover": true,
	"Node.enter": true,
	"Node.exit":  true,
	"Node.cycle": true,
}

// boxed reports whether the struct of m holds the field f behind a pointer:
// a message that holds m again through single fields, which a struct can
// hold no other way, or one of rustSpare.
func (w *rustWriter) boxed(m *message, f *field) bool {
	if f.message == nil || f.repeated {
		return false
	}
	if name := m.name + "." + f.name; rustSpare[name] {
		w.spared[name] = true
		return true
	}
	seen := map[*message]bool{}
	var holds func(from *message) bool
	holds = func(from *message) bool {
		if from == m {
			return true
		}
		if seen[from] {
			return false
		}
		seen[from] = true
		for _, inner := range from.fields {
			if inner.message != nil && !inner.repeated && holds(inner.message) {
				return true
			}
		}
		return false
	}
	return holds(f.message)
}

// copies reports whether a value of f is a Copy type, which the library
// passes by value.
func (w *rustWriter) copies(f *field) bool {
	if f.message != nil {
		return false
	}
	return f.kind != descriptorpb.FieldDescriptorProto_TYPE_STRING && f.kind != descriptorpb.FieldDescriptorProto_TYPE_BYTES
}

// packs reports whether a repeated f packs into one record.
func (w *rustWriter) packs(f *field) bool {
	return w.copies(f)
}

// base returns the Rust type that holds one value of a field.
func (w *rustWriter) base(f *field) string {
	if c := classOf(f); c != nil {
		return c.name
	}
	switch {
	case f.message != nil:
		return w.messageName(f.message)
	case f.enum != nil:
		return rustType(f.enum.name)
	}
	return rustKinds[f.kind].typ
}

// memberType returns the type of the member of m that holds f. A message
// holding only a oneof has no value without a case, so a single one is
// optional.
func (w *rustWriter) memberType(m *message, f *field) string {
	t := w.base(f)
	switch {
	case f.repeated:
		return "Vec<" + t + ">"
	case w.nobody(f):
		return "Option<" + t + ">"
	case w.boxed(m, f):
		return "Option<Box<" + t + ">>"
	case w.optional(f), f.message != nil && f.message.isUnion():
		return "Option<" + t + ">"
	}
	return t
}

// optional reports whether a member holding f may be None.
func (w *rustWriter) optional(f *field) bool {
	return f.optional || w.absent[f]
}

// nobody reports whether f holds a player the game may leave out: its slot is
// -1 where no player stands behind what the message reports, such as the
// victim of a kill that is a unit. The schema says so in the field's comment.
// The library holds such a field as an Option, so a mod cannot take nobody
// for a player.
func (w *rustWriter) nobody(f *field) bool {
	c := classOf(f)
	return c != nil && c.interned && strings.Contains(f.doc, "-1")
}

// borrowed returns the type of one value of f as an argument of a call.
func (w *rustWriter) borrowed(f *field) string {
	switch {
	case f.message != nil:
		return "&" + w.messageName(f.message)
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_STRING:
		return "&str"
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_BYTES:
		return "&[u8]"
	}
	return w.base(f)
}

// paramType returns the type of one positional parameter of c.
func (w *rustWriter) paramType(c *call, p *param) string {
	if p.oneof != nil {
		return "&" + w.argumentName(c.method.request, p.oneof)
	}
	f := p.field
	switch {
	case f.repeated && f.kind == descriptorpb.FieldDescriptorProto_TYPE_STRING:
		return "&[&str]"
	case f.repeated:
		return "&[" + w.base(f) + "]"
	case f.optional:
		return "Option<" + w.borrowed(f) + ">"
	case w.text(f):
		return "impl AsRef<str>"
	}
	return w.borrowed(f)
}

// text reports whether f is a single string a call always takes, which it
// takes as anything that is text: a literal, or what format! makes.
func (w *rustWriter) text(f *field) bool {
	return f.kind == descriptorpb.FieldDescriptorProto_TYPE_STRING && !f.repeated && !f.optional
}

// one returns the statement that encodes v as one value of f, with its tag.
// v is a value for a Copy type and a reference for any other.
func (w *rustWriter) one(f *field, v string) string {
	switch {
	case classOf(f) != nil:
		return fmt.Sprintf("wire::%s(out, %d, %s),", rustKinds[f.kind].name, f.number, w.key(f, v))
	case f.enum != nil:
		return fmt.Sprintf("wire::int32(out, %d, %s as i32),", f.number, v)
	case f.message != nil && f.message.isUnion():
		return fmt.Sprintf("wire::nested(out, %d, |out| %s.encode(out)),", f.number, strings.TrimPrefix(v, "&"))
	case f.message != nil:
		return fmt.Sprintf("wire::message(out, %d, %s),", f.number, v)
	case f.hero:
		return fmt.Sprintf("wire::string(out, %d, hero_name(%s)),", f.number, v)
	}
	return fmt.Sprintf("wire::%s(out, %d, %s),", rustKinds[f.kind].name, f.number, v)
}

// key returns the expression that reads the key of v, a value of the class f
// holds, as f's type: a field may carry a slot as a uint32.
func (w *rustWriter) key(f *field, v string) string {
	c := classOf(f)
	if typ := rustKinds[f.kind].typ; rustKeys[c.goType] != typ {
		return c.rustRead(v) + " as " + typ
	}
	return c.rustRead(v)
}

// statement returns one's match arm as a statement.
func statement(arm string) string {
	return strings.TrimSuffix(arm, ",") + ";"
}

// present returns the condition under which a single v of f is not the zero
// value the receiver assumes.
func (w *rustWriter) present(f *field, v string) string {
	switch {
	case classOf(f) != nil:
		return classOf(f).rustRead(v) + " != 0"
	case f.enum != nil:
		return v + " as i32 != 0"
	}
	switch f.kind {
	case descriptorpb.FieldDescriptorProto_TYPE_BOOL:
		return v
	case descriptorpb.FieldDescriptorProto_TYPE_DOUBLE, descriptorpb.FieldDescriptorProto_TYPE_FLOAT:
		return v + " != 0.0"
	case descriptorpb.FieldDescriptorProto_TYPE_STRING, descriptorpb.FieldDescriptorProto_TYPE_BYTES:
		return "!" + v + ".is_empty()"
	}
	return v + " != 0"
}

// encode returns the statements that encode f from place: a member of a
// struct, or an argument of a call when argument is true. boxed marks a
// member the struct holds behind a pointer. It leaves out what the receiver
// assumes: a zero, an empty list, an optional value that is not set, and a
// message that sets nothing. A receiver may tell a message that is there from
// one that is not, as the renderer draws the gradient a style has even when
// it is empty, so a message a mod left as its default must not travel.
func (w *rustWriter) encode(f *field, place string, argument, boxed bool) []string {
	// An argument is already a reference where a member is a value.
	ref := place
	if !argument {
		ref = "&" + place
	}
	item := "v"
	if w.copies(f) {
		item = "*v"
	}
	switch {
	case !argument && w.nobody(f):
		slot := classOf(f).rustRead("v")
		return []string{
			fmt.Sprintf("match %s {", place),
			fmt.Sprintf("    Some(v) if %s == 0 => {}", slot),
			fmt.Sprintf("    Some(v) => wire::int32(out, %d, %s),", f.number, slot),
			fmt.Sprintf("    None => wire::int32(out, %d, -1),", f.number),
			"}",
		}
	case f.repeated && w.packs(f):
		kind := rustKinds[f.kind].name
		if f.enum != nil {
			item += " as i32"
		}
		return []string{fmt.Sprintf("wire::packed(out, %d, %s, |out, v| wire::raw::%s(out, %s));", f.number, ref, kind, item)}
	case f.repeated:
		return []string{fmt.Sprintf("for v in %s {", ref), "    " + statement(w.one(f, "v")), "}"}
	case boxed:
		return []string{fmt.Sprintf("if let Some(v) = %s {", ref), "    " + statement(w.one(f, "&**v")), "}"}
	case w.optional(f) && w.copies(f):
		return []string{fmt.Sprintf("if let Some(v) = %s {", place), "    " + statement(w.one(f, "v")), "}"}
	case w.optional(f), !argument && f.message != nil && f.message.isUnion():
		return []string{fmt.Sprintf("if let Some(v) = %s {", ref), "    " + statement(w.one(f, "v")), "}"}
	case f.message != nil && f.message.isUnion():
		return []string{statement(w.one(f, ref))}
	case f.message != nil:
		set := strings.TrimPrefix(ref, "&")
		if argument {
			set = "*" + place
		}
		return []string{fmt.Sprintf("if %s != %s::default() {", set, w.messageName(f.message)), "    " + statement(w.one(f, ref)), "}"}
	case w.copies(f):
		return []string{fmt.Sprintf("if %s {", w.present(f, place)), "    " + statement(w.one(f, place)), "}"}
	}
	return []string{fmt.Sprintf("if %s {", w.present(f, place)), "    " + statement(w.one(f, ref)), "}"}
}

// value returns the expression that reads one value of f from the reader r,
// whose wire type is kind. A message holding only a oneof reads as an Option.
func (w *rustWriter) value(f *field) (string, error) {
	kind, ok := rustKinds[f.kind]
	switch {
	case classOf(f) != nil:
		key := fmt.Sprintf("r.%s(kind)?", kind.name)
		if c := classOf(f); rustKeys[c.goType] != kind.typ {
			key += " as " + rustKeys[c.goType]
		}
		return classOf(f).rustMake(key), nil
	case f.enum != nil:
		return fmt.Sprintf("%s::from_i32(r.int32(kind)?)", rustType(f.enum.name)), nil
	case f.message != nil:
		return fmt.Sprintf("%s::decode(r.bytes(kind)?)?", w.messageName(f.message)), nil
	case !ok:
		return "", fmt.Errorf("the Rust codec has no %s for %s", f.kind, f.name)
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_BYTES:
		return "r.bytes(kind)?.to_vec()", nil
	}
	return fmt.Sprintf("r.%s(kind)?", kind.name), nil
}

// decode returns the expression that reads the field f of m into place: the
// member of a struct, or the result of a call.
func (w *rustWriter) decode(m *message, f *field, place string) (string, error) {
	value, err := w.value(f)
	if err != nil {
		return "", err
	}
	union := f.message != nil && f.message.isUnion()
	switch {
	case f.oneof == nil && w.nobody(f) && place != "result":
		return fmt.Sprintf("%s = %s", place, classOf(f).rustKnown("r.int32(kind)?")), nil
	case f.oneof != nil && union:
		return "", fmt.Errorf("the case %s holds a message that is itself a union", f.name)
	case f.oneof != nil:
		if w.boxed(m, f) {
			value = "Box::new(" + value + ")"
		}
		return fmt.Sprintf("message.%s = Some(%s::%s(%s))", rustIdent(f.oneof.name), w.oneofName(m, f.oneof), rustVariant(f.name), value), nil
	case f.repeated && w.packs(f):
		kind := rustKinds[f.kind]
		return fmt.Sprintf("r.repeated(kind, wire::%s, &mut %s, |r, kind| Ok(%s))?", kind.wire, place, value), nil
	case f.repeated && union:
		return fmt.Sprintf("if let Some(v) = %s { %s.push(v) }", value, place), nil
	case f.repeated:
		return fmt.Sprintf("%s.push(%s)", place, value), nil
	case union:
		return fmt.Sprintf("%s = %s", place, value), nil
	case w.boxed(m, f):
		return fmt.Sprintf("%s = Some(Box::new(%s))", place, value), nil
	case w.optional(f):
		return fmt.Sprintf("%s = Some(%s)", place, value), nil
	}
	return fmt.Sprintf("%s = %s", place, value), nil
}

// writeClass writes one class with its calls as methods. The library writes
// an interned class by hand, since its value carries the connection the mod
// saw it in.
func (w *rustWriter) writeClass(c *class) error {
	if !c.interned {
		typ, ok := rustKeys[c.goType]
		if !ok {
			return fmt.Errorf("the class %s has a key of type %s", c.name, c.goType)
		}
		w.doc(0, c.doc)
		w.line(0, "#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]")
		w.line(0, "pub struct %s {", c.name)
		w.doc(1, c.keyDoc)
		w.line(1, "pub %s: %s,", rustIdent(snake(c.key)), typ)
		w.line(0, "}")
		w.line(0, "")
	}
	w.line(0, "impl %s {", c.name)
	first := true
	for _, call := range w.calls {
		if call.class != c {
			continue
		}
		if !first {
			w.line(0, "")
		}
		first = false
		if err := w.writeCall(call, 1); err != nil {
			return fmt.Errorf("%s: %w", call.method.name, err)
		}
	}
	w.line(0, "}")
	w.line(0, "")
	return nil
}

// rustKeys maps the Go type of a class's key to its Rust type.
var rustKeys = map[string]string{"int32": "i32", "uint32": "u32"}

// rustRead returns the expression that reads the key of v, a value of class c
// or a reference to one.
func (c *class) rustRead(v string) string {
	v = strings.TrimPrefix(v, "*")
	if c.interned {
		return v + "." + rustIdent(snake(c.key)) + "()"
	}
	return v + "." + rustIdent(snake(c.key))
}

// rustMake returns the expression that makes the value of class c with key.
func (c *class) rustMake(key string) string {
	if c.interned {
		return c.name + "::of(" + key + ")"
	}
	return fmt.Sprintf("%s { %s: %s }", c.name, rustIdent(snake(c.key)), key)
}

// rustKnown returns the expression that makes the value of the interned class
// c with key, or None for the key that names nobody.
func (c *class) rustKnown(key string) string {
	return c.name + "::known(" + key + ")"
}

// writeCall writes one call at depth levels of indentation: a method of its
// class, or else a function of the module. It encodes the arguments straight
// into the call and reads the result straight from the reply, so neither the
// request nor the response is a type of the library.
func (w *rustWriter) writeCall(c *call, depth int) error {
	name := rustIdent(snake(c.name))
	if renamed, ok := rustNames[c.method.name]; ok {
		name = renamed
	}
	request := c.method.request

	// Declare the call. A class is a Copy value, so its method takes it whole.
	var params []string
	if c.class != nil {
		params = append(params, "self")
	}
	if c.options {
		params = append(params, "options: &"+w.messageName(request))
	}
	for _, p := range c.params {
		params = append(params, fmt.Sprintf("%s: %s", rustIdent(p.paramName()), w.paramType(c, p)))
	}

	// Encode the receiver, then the options or each argument.
	var encode []string
	if c.receiver != nil {
		encode = append(encode, w.encode(c.receiver, "self", true, false)...)
	}
	if c.options {
		encode = append(encode, "options.encode(out);")
	}
	for _, p := range c.params {
		place := rustIdent(p.paramName())
		if o := p.oneof; o != nil {
			encode = append(encode, fmt.Sprintf("match %s {", place))
			for _, f := range o.fields {
				encode = append(encode, fmt.Sprintf("    %s::%s(v) => %s", w.argumentName(request, o), rustVariant(f.name), w.one(f, w.caseValue(request, f))))
			}
			encode = append(encode, "}")
			continue
		}
		if w.text(p.field) {
			place += ".as_ref()"
		}
		encode = append(encode, w.encode(p.field, place, true, false)...)
	}
	write := "|_| {}"
	if len(encode) != 0 {
		write = "|out| {"
	}

	// A call that answers nothing returns whether it succeeded.
	w.doc(depth, rename(c.method.doc, c.method.name, name))
	if c.result == nil {
		w.line(depth, "pub fn %s(%s) -> bool {", name, strings.Join(params, ", "))
		if len(encode) == 0 {
			w.line(depth+1, "host::send(%q, %s)", c.method.name, write)
		} else {
			w.line(depth+1, "host::send(%q, %s", c.method.name, write)
			w.lines(depth+2, encode)
			w.line(depth+1, "})")
		}
		w.line(depth, "}")
		return nil
	}

	// Any other returns its response's field: a list empty when the call
	// fails, a plain bool false, and anything else None. A message, and a
	// field marked optional, is also None when the host leaves it out.
	f := c.result
	value, err := w.value(f)
	if err != nil {
		return err
	}
	result, start, after := "Option<"+w.base(f)+">", "Default::default()", ""
	arm := "result = " + value
	switch {
	case f.repeated:
		result, start, after = "Vec<"+w.base(f)+">", "Vec::new()", ".unwrap_or_default()"
		if arm, err = w.decode(c.method.response, f, "result"); err != nil {
			return err
		}
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_BOOL && !f.optional:
		result, start, after = "bool", "false", ".unwrap_or(false)"
	case f.message != nil && f.message.isUnion():
		start, after = "None", ".flatten()"
	case f.optional, f.message != nil:
		start, after, arm = "None", ".flatten()", "result = Some("+value+")"
	}
	w.line(depth, "pub fn %s(%s) -> %s {", name, strings.Join(params, ", "), result)
	w.line(depth+1, "host::call(")
	w.line(depth+2, "%q,", c.method.name)
	if len(encode) == 0 {
		w.line(depth+2, "%s,", write)
	} else {
		w.line(depth+2, "%s", write)
		w.lines(depth+3, encode)
		w.line(depth+2, "},")
	}
	w.line(depth+2, "|r| {")
	w.line(depth+3, "let mut result: %s = %s;", w.resultHolder(f), start)
	w.line(depth+3, "while let Some((number, kind)) = r.field()? {")
	w.line(depth+4, "match number {")
	w.line(depth+5, "%d => %s,", f.number, arm)
	w.line(depth+5, "_ => r.skip(kind)?,")
	w.line(depth+4, "}")
	w.line(depth+3, "}")
	w.line(depth+3, "Ok(result)")
	w.line(depth+2, "},")
	w.line(depth+1, ")%s", after)
	w.line(depth, "}")
	return nil
}

// resultHolder returns the type of the variable a call reads its result into.
func (w *rustWriter) resultHolder(f *field) string {
	switch {
	case f.repeated:
		return "Vec<" + w.base(f) + ">"
	case f.optional, f.message != nil:
		return "Option<" + w.base(f) + ">"
	}
	return w.base(f)
}

// rustAnswered are the events the handwritten library answers for the mod:
// Start's answer says which events the mod wants, which the library knows.
var rustAnswered = map[string]bool{"Start": true}

// rustEvent is how the Rust library presents an event the game sends only to
// a mod that asked for it: the trait a mod implements to handle it, and the
// member of StartResult that asks for it.
type rustEvent struct {
	trait string
	flag  string
}

// rustEvents maps each Mod method the game sends on request to its trait.
// Implementing the trait is the request, so a mod never asks for an event it
// ignores, and never forgets to ask for one it handles.
var rustEvents = map[string]rustEvent{
	"Damage":       {"OnDamage", "damage"},
	"Damaged":      {"OnDamaged", "damaged"},
	"Chat":         {"OnChat", "chat"},
	"PlayerJoined": {"OnJoin", "joins"},
	"PlayerLeft":   {"OnJoin", "joins"},
	"AbilityCast":  {"OnCast", "casts"},
	"Killed":       {"OnKill", "kills"},
	"Healed":       {"OnHeal", "heals"},
	"LevelChanged": {"OnLevel", "levels"},
	"Melee":        {"OnMelee", "melees"},
	"Parried":      {"OnParry", "parries"},
}

// rustHandled are the events the handwritten library handles whole, through
// the handlers a mod registers: modifier_event, serve and call_service_later
// by name, and a button's and an input's on the element.
var rustHandled = map[string]bool{
	"ModifierFired":  true,
	"Serve":          true,
	"ServiceReplied": true,
	"UiPress":        true,
	"UiInput":        true,
}

// rustMade are the events the handwritten library makes from the game's. Each
// has a trait, as an event the game sends on request has, so the library
// knows at the mod's start whether to ask the game for what it makes it from.
var rustMade = []handler{{
	trait:  "OnSpawn",
	name:   "spawned",
	params: ", player: Player, pawn: &Pawn",
	types:  ", Player, &Pawn",
	doc: "OnSpawn handles each hero entering play: a player's first hero after\n" +
		"joining, and each respawn. The player has a hero to move, equip and read\n" +
		"from then on, which OnJoin does not promise. The library hears it from the\n" +
		"game's PLAYER_RESPAWNED event, before the frame.",
	methodDoc: "spawned handles the hero pawn of player entering play.",
}}

// handler is one event as the Rust library writes it.
type handler struct {
	// method is the event in the schema, or nil for one the library makes.
	method *method
	// trait is the trait a mod implements to ask for the event, or empty for
	// an event the game always sends.
	trait string
	// name is the name of the method that handles the event.
	name string
	// params are the method's parameters after the mod, each with its leading
	// comma, and types are their types alone.
	params, types string
	// result is the type the method returns, or empty for one that answers
	// nothing.
	result string
	// doc and methodDoc describe the trait and the method of an event the
	// library makes.
	doc, methodDoc string
}

// handlerOf returns the event m as the Rust library writes it.
func (w *rustWriter) handlerOf(m *method) handler {
	h := handler{method: m, name: rustIdent(snake(m.name))}
	h.methodDoc = rename(m.doc, m.name, h.name)
	if !m.request.isEmpty() {
		h.params = ", event: &" + w.messageName(m.request)
		h.types = ", &" + w.messageName(m.request)
	}
	if !m.response.isEmpty() && !rustAnswered[m.name] {
		h.result = w.messageName(m.response)
	}
	return h
}

// pointer returns the type of a function that handles h on a mod M.
func (h handler) pointer() string {
	pointer := "fn(&mut M" + h.types + ")"
	if h.result != "" {
		pointer += " -> " + h.result
	}
	return pointer
}

// call returns the expression that runs h, which handle names, with
// arguments and then the decoded request, and appends its encoded response to
// out.
func (w *rustWriter) call(h handler, handle string, arguments ...string) string {
	if h.params != "" {
		arguments = append(arguments, fmt.Sprintf("&%s::decode(request)?", w.messageName(h.method.request)))
	}
	call := handle + "(" + strings.Join(arguments, ", ") + ")"
	if h.result != "" {
		call += ".encode(out)"
	}
	return call
}

// writeMod writes the trait of the events the game always delivers to the
// mod, a trait for each event it delivers on request, and the dispatch that
// runs one event.
func (w *rustWriter) writeMod() error {
	// Sort the events into the ones the game always sends and the ones a mod
	// asks for, by trait in schema order.
	wants := w.s.messages[".modlock.wasm.StartResult"]
	if wants == nil {
		return fmt.Errorf("the schema lacks StartResult")
	}
	var always, asked []handler
	var traits []string
	byTrait := map[string][]handler{}
	handled := 0
	for _, m := range w.s.mod.methods {
		if m.request.isUnion() || m.response.isUnion() {
			return fmt.Errorf("%s: an event carries a message, not a union", m.name)
		}
		if rustHandled[m.name] {
			handled++
			continue
		}
		h := w.handlerOf(m)
		event, ok := rustEvents[m.name]
		if !ok {
			always = append(always, h)
			continue
		}
		h.trait = event.trait
		if byTrait[event.trait] == nil {
			traits = append(traits, event.trait)
		}
		byTrait[event.trait] = append(byTrait[event.trait], h)
		asked = append(asked, h)
	}
	if len(asked) != len(rustEvents) || handled != len(rustHandled) {
		return fmt.Errorf("rustEvents or rustHandled names a method the Mod service lacks")
	}

	// held are the events a mod has a trait for: the ones the game sends on
	// request, then the ones the library makes.
	held := append(append([]handler{}, asked...), rustMade...)

	// The events the game always sends are the methods of Mod.
	w.doc(0, "Mod handles the events the game always delivers to the mod. A mod\nimplements the ones it acts on; each of the rest does nothing. The events\nthe game sends only on request have a trait each, such as OnKill.")
	w.line(0, "#[allow(unused_variables)]")
	w.line(0, "pub trait Mod {")
	for i, h := range always {
		if i != 0 {
			w.line(0, "")
		}
		w.doc(1, h.methodDoc)
		w.writeHandler(h, true)
	}
	w.line(0, "}")
	w.line(0, "")

	// Each event the game sends on request is a trait, which a mod
	// implements to ask for it. A trait of one event requires its method.
	for _, trait := range traits {
		handlers := byTrait[trait]
		flag := rustEvents[handlers[0].method.name].flag
		doc := ""
		for _, f := range wants.fields {
			if f.name == flag && f.kind == descriptorpb.FieldDescriptorProto_TYPE_BOOL {
				doc = rename(f.doc, camel(f.name), trait)
			}
		}
		if doc == "" {
			return fmt.Errorf("%s: StartResult has no bool %s", trait, flag)
		}
		w.doc(0, doc+"\nThe game sends it only to a mod that implements "+trait+".")
		w.line(0, "#[allow(unused_variables)]")
		w.line(0, "pub trait %s: Mod {", trait)
		for i, h := range handlers {
			if i != 0 {
				w.line(0, "")
			}
			w.doc(1, h.methodDoc)
			w.writeHandler(h, len(handlers) > 1)
		}
		w.line(0, "}")
		w.line(0, "")
	}
	for _, h := range rustMade {
		w.doc(0, h.doc)
		w.line(0, "pub trait %s: Mod {", h.trait)
		w.doc(1, h.methodDoc)
		w.writeHandler(h, false)
		w.line(0, "}")
		w.line(0, "")
	}

	// Events holds the handlers of the events a mod asked for.
	w.doc(0, "Events holds a mod's handler of each event it has a trait for, or None for\nan event the mod does not handle. The run! macro fills it from the traits\nthe mod implements.")
	w.line(0, "pub struct Events<M> {")
	for _, h := range held {
		w.line(1, "pub %s: Option<%s>,", h.name, h.pointer())
	}
	w.line(0, "}")
	w.line(0, "")
	w.line(0, "impl<M> Events<M> {")
	w.doc(1, "ask sets in wants the request for each event the mod handles.")
	w.line(1, "pub fn ask(&self, wants: &mut StartResult) {")
	for _, trait := range traits {
		var held []string
		for _, h := range byTrait[trait] {
			held = append(held, "self."+h.name+".is_some()")
		}
		w.line(2, "wants.%s = %s;", rustEvents[byTrait[trait][0].method.name].flag, strings.Join(held, " || "))
	}
	w.line(1, "}")
	w.line(0, "")
	w.doc(1, "serve runs the event method on the mod m with its encoded request and\nappends the encoded response to out. It returns false for a method that\nis no event the game sends on request.")
	w.line(1, "pub fn serve(&self, m: &mut M, method: &str, request: &[u8], out: &mut Vec<u8>) -> Result<bool, wire::Error> {")
	w.line(2, "match method {")
	for _, h := range asked {
		w.line(3, "%q => if let Some(handle) = self.%s { %s },", h.method.name, h.name, w.call(h, "handle", "m"))
	}
	w.line(3, "_ => return Ok(false),")
	w.line(2, "}")
	w.line(2, "Ok(true)")
	w.line(1, "}")
	w.line(0, "}")
	w.line(0, "")

	// The dispatch of the events the game always sends.
	w.doc(0, "serve_mod runs the event method on handlers with its encoded request and\nappends the encoded response to out. It returns false for a method the\nlibrary does not know.")
	w.line(0, "pub fn serve_mod<M: Mod + ?Sized>(handlers: &mut M, method: &str, request: &[u8], out: &mut Vec<u8>) -> Result<bool, wire::Error> {")
	w.line(1, "match method {")
	for _, h := range always {
		w.line(2, "%q => %s,", h.method.name, w.call(h, "handlers."+h.name))
	}
	w.line(2, "_ => return Ok(false),")
	w.line(1, "}")
	w.line(1, "Ok(true)")
	w.line(0, "}")
	w.line(0, "")

	// probe finds the traits a mod implements where the module names the mod:
	// a method call on a value picks the impl for the type itself, which
	// needs the trait, before the impl for a reference to it, which does not.
	w.doc(0, "probe finds which of the events the game sends on request a mod handles.\nThe events! macro calls it; a mod has no need to.")
	w.line(0, "#[doc(hidden)]")
	w.line(0, "pub mod probe {")
	w.line(1, "use super::*;")
	w.line(0, "")
	w.doc(1, "Probe stands for the mod M.")
	w.line(1, "pub struct Probe<M>(core::marker::PhantomData<M>);")
	w.line(0, "")
	w.line(1, "impl<M> Probe<M> {")
	w.doc(2, "of returns the Probe of the mod make makes.")
	w.line(2, "pub fn of(_make: &impl FnOnce() -> M) -> Self {")
	w.line(3, "Probe(core::marker::PhantomData)")
	w.line(2, "}")
	w.line(1, "}")
	for _, h := range held {
		trait := h.trait
		name := camel(h.name)
		w.line(0, "")
		w.line(1, "pub trait %sHandled<M> {", name)
		w.line(2, "fn %s(&self) -> Option<%s>;", h.name, h.pointer())
		w.line(1, "}")
		w.line(0, "")
		w.line(1, "impl<M: %s> %sHandled<M> for Probe<M> {", trait, name)
		w.line(2, "fn %s(&self) -> Option<%s> {", h.name, h.pointer())
		w.line(3, "Some(<M as %s>::%s)", trait, h.name)
		w.line(2, "}")
		w.line(1, "}")
		w.line(0, "")
		w.line(1, "pub trait %sIgnored<M> {", name)
		w.line(2, "fn %s(&self) -> Option<%s>;", h.name, h.pointer())
		w.line(1, "}")
		w.line(0, "")
		w.line(1, "impl<M> %sIgnored<M> for &Probe<M> {", name)
		w.line(2, "fn %s(&self) -> Option<%s> {", h.name, h.pointer())
		w.line(3, "None")
		w.line(2, "}")
		w.line(1, "}")
	}
	w.line(0, "}")
	w.line(0, "")

	w.doc(0, "events! returns the Events of the mod its argument makes: the handler of\neach event whose trait the mod implements. The run! macro calls it.")
	w.line(0, "#[doc(hidden)]")
	w.line(0, "#[macro_export]")
	w.line(0, "macro_rules! events {")
	w.line(1, "($make:expr) => {{")
	w.line(2, "#[allow(unused_imports)]")
	w.line(2, "use $crate::probe::*;")
	w.line(2, "let probe = $crate::probe::Probe::of(&$make);")
	w.line(2, "#[allow(clippy::needless_borrow)]")
	w.line(2, "$crate::Events {")
	for _, h := range held {
		w.line(3, "%s: (&probe).%s(),", h.name, h.name)
	}
	w.line(2, "}")
	w.line(1, "}};")
	w.line(0, "}")
	w.line(0, "")
	return nil
}

// writeHandler writes the method of the event h in a trait: with a body that
// does nothing and answers nothing when optional, and required otherwise.
func (w *rustWriter) writeHandler(h handler, optional bool) {
	signature := fmt.Sprintf("fn %s(&mut self%s)", h.name, h.params)
	if h.result != "" {
		signature += " -> " + h.result
	}
	switch {
	case !optional:
		w.line(1, "%s;", signature)
	case h.result == "":
		w.line(1, "%s {}", signature)
	default:
		w.line(1, "%s {", signature)
		w.line(2, "Default::default()")
		w.line(1, "}")
	}
}

// writeRoundTrip writes the function the library's tests decode and encode
// each message with, by its name in the schema.
func (w *rustWriter) writeRoundTrip() {
	w.doc(0, "round_trip decodes data as the message the schema names name and returns\nit encoded again, or None for a name the library does not declare.")
	w.line(0, "#[cfg(test)]")
	w.line(0, "pub(crate) fn round_trip(name: &str, data: &[u8]) -> Option<Result<Vec<u8>, wire::Error>> {")
	w.line(1, "let mut out = Vec::new();")
	w.line(1, "let decoded = match name {")
	for _, m := range w.s.messageOrder {
		switch {
		case !w.types.seen[m] || m.isEmpty() || w.omitted[m] != nil:
		case m.isUnion():
			w.line(2, "%q => %s::decode(data).map(|m| if let Some(m) = m { m.encode(&mut out) }),", m.name, w.messageName(m))
		default:
			w.line(2, "%q => %s::decode(data).map(|m| m.encode(&mut out)),", m.name, w.messageName(m))
		}
	}
	w.line(2, "_ => return None,")
	w.line(1, "};")
	w.line(1, "Some(decoded.map(|()| out))")
	w.line(0, "}")
}

// rustType returns the Rust name of a type the schema names name, which joins
// a nested name with underscores.
func rustType(name string) string {
	return strings.ReplaceAll(name, "_", "")
}

// rustVariant returns the name of an enum variant for name, a schema name or
// one in lowerCamel form.
func rustVariant(name string) string {
	variant := camel(name)
	switch {
	case variant == "" || unicode.IsDigit(rune(variant[0])):
		return "V" + variant
	case variant == "Self":
		return "Self_"
	}
	return variant
}

// rustKeywords are the reserved words of Rust, which a name cannot use.
var rustKeywords = set(strings.Fields(`abstract as async await become box break const continue crate do dyn
	else enum extern false final fn for gen if impl in let loop macro match mod move mut override
	priv pub ref return self static struct super trait true try type typeof unsafe unsized use
	virtual where while yield`))

// rustUnraw are the reserved words Rust takes no raw identifier of.
var rustUnraw = set([]string{"crate", "self", "super", "Self", "_"})

// rustIdent returns name as a Rust identifier: a reserved word as the raw
// identifier of it, such as r#type, so the name stays the schema's, or with
// an underscore after it when Rust has no raw identifier of the word.
func rustIdent(name string) string {
	switch {
	case rustUnraw[name]:
		return name + "_"
	case rustKeywords[name]:
		return "r#" + name
	}
	return name
}

